function test_results_domain_contract(~)
%TEST_RESULTS_DOMAIN_CONTRACT Validate maintained results-domain behavior.

    temporaryRoot = tempname;
    fixture = create_results_fixture(temporaryRoot);
    cleanup = onCleanup(@() remove_temporary_root(temporaryRoot));
    write_acquisition_table(fixture.paramsFile, fixture.acquisitionTable);

    assembled = oce.results.buildSubexperimentResultSet( ...
        fixture.experimentRoot, fixture.subExperiment, ...
        "frequency_Hz", "rep_id", 'MissingResultMode', 'skip');
    aligned = oce.results.alignDispersionFrequencies(assembled);
    repetitions = oce.results.summarizeRepetitions(aligned);
    angles = oce.results.summarizeAngles(repetitions);
    summaryTable = oce.results.buildConditionSummaryTable(angles);

    assert_summary_schema(assembled, aligned, repetitions, angles, summaryTable);
    assert_result_folder_contract(assembled, fixture);
    assert_retired_schema_rejected(repetitions);
    assert_condition_labels();
    assert_error_contracts(fixture);
    assert_missing_modes(fixture);
    assert_duplicate_modes(fixture);

    clear cleanup
end

function assert_summary_schema(assembled, aligned, repetitions, angles, summaryTable)
    if isempty(assembled.data) || isempty(aligned.data) || ...
            ~isfield(repetitions, 'summary') || ~isfield(angles, 'summary') || ...
            isempty(summaryTable) || height(summaryTable) == 0
        error('OCE:ResultsTest:SummarySchema', ...
            'Results-domain processing did not produce maintained outputs.');
    end
    requiredRepetition = {'repetition_mean_data', 'repetition_std_data'};
    if any(~isfield(repetitions.summary, requiredRepetition))
        error('OCE:ResultsTest:SummarySchema', ...
            'Repetition summary fields are missing.');
    end
    requiredAngles = {'angle_mean_data', 'angle_std_data', 'angle_n_data'};
    if any(~isfield(angles.summary, requiredAngles)) || ...
            isfield(angles.summary, 'angle_uncertainty_data')
        error('OCE:ResultsTest:SummarySchema', ...
            'Angular summary schema is invalid or retains a retired alias.');
    end
end

function assert_result_folder_contract(assembled, fixture)
    expectedFolders = strings(height(fixture.acquisitionTable), 1);
    for rowIndex = 1:height(fixture.acquisitionTable)
        [~, acquisitionName, ~] = fileparts( ...
            fixture.acquisitionTable.filename(rowIndex));
        expectedFolders(rowIndex) = string(fullfile( ...
            fixture.resultsRoot, acquisitionName));
    end
    if assembled.source.result_folder_key ~= "filename" || ...
            ~isequal(string(assembled.source.result_folders), expectedFolders)
        error('OCE:ResultsTest:ResultFolderContract', ...
            ['Results must be located by acquisition filename without its ' ...
             'extension, independently of run_id.']);
    end
end

function assert_retired_schema_rejected(repetitions)
    retired = repetitions;
    retired.repetition_mean_data = retired.summary.repetition_mean_data;
    retired.repetition_std_data = retired.summary.repetition_std_data;
    retired.summary = rmfield(retired.summary, ...
        {'repetition_mean_data', 'repetition_std_data'});
    captured = capture_error(@() oce.results.summarizeAngles(retired));
    assert_captured_error(captured, "", ...
        "Repetition summary data not found", ...
        'retired repetition schema');
end

function assert_condition_labels()
    keys = ["frequency_Hz", "voltage_mVpp", "custom_key"];
    values = {{'2500'}, {'50'}, {'A B'}};
    indices = {1, 1, 1};
    [knownLabel, knownFile] = oce.results.formatConditionLabel( ...
        keys, values, indices, [1 2]);
    [fallbackLabel, fallbackFile] = oce.results.formatConditionLabel( ...
        keys, values, indices, 3);
    [emptyLabel, emptyFile] = oce.results.formatConditionLabel( ...
        keys, values, indices, []);
    if knownLabel ~= "2500 Hz - 50 mVpp" || knownFile ~= "2500Hz_50mVpp" || ...
            fallbackLabel ~= "custom key: A B" || fallbackFile ~= "custom_key_A_B" || ...
            emptyLabel ~= "All conditions" || emptyFile ~= "AllConditions"
        error('OCE:ResultsTest:ConditionLabel', ...
            'Condition label/file formatting changed.');
    end
end

function assert_error_contracts(fixture)
    missingArguments = capture_error(@() ...
        oce.pipeline.runSubexperimentSummary("only-one"));
    retiredLoadFile = capture_error(@() ...
        oce.results.buildSubexperimentResultSet( ...
        fixture.experimentRoot, fixture.subExperiment, ...
        "frequency_Hz", "rep_id", 'LoadFile', 'Other.mat'));
    invalidMissingMode = capture_error(@() ...
        oce.results.buildSubexperimentResultSet( ...
        fixture.experimentRoot, fixture.subExperiment, ...
        "frequency_Hz", "rep_id", 'MissingResultMode', 'invalid'));

    assert_captured_error(missingArguments, "MATLAB:minrhs", ...
        "Not enough input arguments", 'missing summary arguments');
    assert_captured_error(retiredLoadFile, "", "LoadFile", ...
        'retired LoadFile option');
    assert_captured_error(invalidMissingMode, "", ...
        "MissingResultMode must be one of: warn, error, skip", ...
        'invalid MissingResultMode');
end

function assert_missing_modes(fixture)
    write_acquisition_table(fixture.paramsFile, fixture.missingTable);
    warningTranscript = evalc([ ...
        'warnValue = oce.results.buildSubexperimentResultSet(' ...
        'fixture.experimentRoot, fixture.subExperiment, ' ...
        '"frequency_Hz", "rep_id", ''MissingResultMode'', ''warn'');']);
    skipValue = oce.results.buildSubexperimentResultSet( ...
        fixture.experimentRoot, fixture.subExperiment, ...
        "frequency_Hz", "rep_id", 'MissingResultMode', 'skip');
    errorValue = capture_error(@() ...
        oce.results.buildSubexperimentResultSet( ...
        fixture.experimentRoot, fixture.subExperiment, ...
        "frequency_Hz", "rep_id", 'MissingResultMode', 'error'));

    missingMessage = "Processed result not found for row 7:";
    warningText = string(warningTranscript);
    warnRuns = string(warnValue.source.acquisition_table.run_id);
    skipRuns = string(skipValue.source.acquisition_table.run_id);
    warnFrequencies = string(warnValue.design.dimension_values{1});
    skipFrequencies = string(skipValue.design.dimension_values{1});
    if ~contains(warningText, missingMessage) || ...
            ~contains(warningText, "missing_acquisition") || ...
            ~isequaln(warnValue.data, skipValue.data) || ...
            any(warnRuns == "R404") || any(skipRuns == "R404") || ...
            any(warnFrequencies == "5500") || any(skipFrequencies == "5500")
        error('OCE:ResultsTest:MissingMode', ...
            ['warn and skip must both exclude the missing result, while warn ' ...
             'must emit the specific missing-result diagnostic.']);
    end
    assert_captured_error(errorValue, "", missingMessage, ...
        'MissingResultMode=error');
end

function assert_duplicate_modes(fixture)
    write_acquisition_table(fixture.paramsFile, fixture.duplicateTable);
    duplicateError = capture_error(@() ...
        oce.results.buildSubexperimentResultSet( ...
        fixture.experimentRoot, fixture.subExperiment, ...
        "frequency_Hz", "rep_id", 'DuplicateMode', 'error'));
    duplicateFirst = oce.results.buildSubexperimentResultSet( ...
        fixture.experimentRoot, fixture.subExperiment, ...
        "frequency_Hz", "rep_id", 'DuplicateMode', 'first');
    duplicateLast = oce.results.buildSubexperimentResultSet( ...
        fixture.experimentRoot, fixture.subExperiment, ...
        "frequency_Hz", "rep_id", 'DuplicateMode', 'last');

    assert_captured_error(duplicateError, "", ...
        "Duplicate experiment grid assignment detected for values: 2500, 1", ...
        'DuplicateMode=error');
    firstResult = get_grid_result(duplicateFirst, "2500", "1");
    lastResult = get_grid_result(duplicateLast, "2500", "1");
    if string(firstResult.source_run_id) ~= "R001" || ...
            string(lastResult.source_run_id) ~= "R007"
        error('OCE:ResultsTest:DuplicateMode', ...
            ['DuplicateMode=first must retain R001 and DuplicateMode=last ' ...
             'must replace it with R007.']);
    end
end

function value = get_grid_result(experiment, frequency, repetition)
    frequencyValues = string(experiment.design.dimension_values{1});
    repetitionValues = string(experiment.design.dimension_values{2});
    frequencyIndex = find(frequencyValues == frequency, 1);
    repetitionIndex = find(repetitionValues == repetition, 1);
    if isempty(frequencyIndex) || isempty(repetitionIndex)
        error('OCE:ResultsTest:FixtureGrid', ...
            'Requested fixture grid value was not found.');
    end
    value = experiment.data{frequencyIndex, repetitionIndex};
end

function assert_captured_error(captured, expectedIdentifier, messageFragment, label)
    if strlength(expectedIdentifier) > 0 && ...
            captured.identifier ~= expectedIdentifier
        error('OCE:ResultsTest:ExpectedError', ...
            '%s expected identifier=%s; actual=%s.', ...
            label, expectedIdentifier, captured.identifier);
    end
    if strlength(captured.message) == 0 || ...
            ~contains(captured.message, messageFragment)
        error('OCE:ResultsTest:ExpectedError', ...
            '%s did not produce the expected diagnostic: %s.', ...
            label, messageFragment);
    end
end

function captured = capture_error(operation)
    try
        operation();
        captured = struct('identifier', "", 'message', "");
    catch ME
        captured = struct('identifier', string(ME.identifier), ...
            'message', string(ME.message));
    end
end

function write_acquisition_table(paramsFile, acquisition_table)
    save(paramsFile, 'acquisition_table');
end

function remove_temporary_root(pathValue)
    if isfolder(pathValue)
        rmdir(pathValue, 's');
    end
end
