function test_loupas_phase_increment(context) %#ok<INUSD>
%TEST_LOUPAS_PHASE_INCREMENT Permanent phase-increment estimator contract.

    constant = exp(-1i * 0.3) * ones(6, 7);
    figuresBefore = findall(groot, 'Type', 'figure');
    directoryBefore = pwd;
    constantOutput = oce.motion.estimateLoupasPhaseIncrement(constant, 3);
    assert(strcmp(pwd, directoryBefore), 'Loupas changed the working directory.');
    assert(isequal(findall(groot, 'Type', 'figure'), figuresBefore), ...
        'Loupas created a figure.');
    assertExactNumericContract(zeros(4, 6), constantOutput, ...
        'Loupas.constant');

    [rowIndex, timeIndex] = ndgrid(1:6, 1:7);
    linear = exp(-1i * (0.1 + 0.2 * (timeIndex - 1)));
    expectedLinearRow = [ ...
        0.20000000000000001 0.19999999999999993 ...
        0.20000000000000018 0.19999999999999993 ...
        0.19999999999999998 0.20000000000000018];
    assertExactNumericContract(repmat(expectedLinearRow, 4, 1), ...
        oce.motion.estimateLoupasPhaseIncrement(linear, 3), ...
        'Loupas.linearPhase');

    amplitude = (1 + 0.1 * rowIndex) .* ...
        exp(-1i * (0.1 * rowIndex + 0.17 * (timeIndex - 1)));
    expectedAmplitude = [ ...
        0.16733675286210498 0.16733675286210498 0.16733675286210486 0.16733675286210495 0.16733675286210489 0.16733675286210486; ...
        0.16733675286210495 0.16733675286210489 0.16733675286210489 0.16733675286210498 0.16733675286210492 0.16733675286210484; ...
        0.16733675286210495 0.16733675286210486 0.16733675286210486 0.16733675286210503 0.16733675286210489 0.16733675286210486; ...
        0.16733675286210495 0.16733675286210495 0.16733675286210481 0.16733675286210509 0.16733675286210484 0.16733675286210484];
    amplitudeOutput = oce.motion.estimateLoupasPhaseIncrement(amplitude, 3);
    assertExactNumericContract(expectedAmplitude, amplitudeOutput, ...
        'Loupas.amplitude');

    assertExactNumericContract(zeros(4, 6), ...
        oce.motion.estimateLoupasPhaseIncrement(zeros(6, 7), 3), ...
        'Loupas.zeroDenominator');

    nanInput = amplitude;
    nanInput(3, 4) = NaN;
    nanOutput = oce.motion.estimateLoupasPhaseIncrement(nanInput, 3);
    expectedNaNMask = false(4, 6);
    expectedNaNMask(1:3, 3:4) = true;
    assert(isequal(isnan(nanOutput), expectedNaNMask), ...
        'Loupas NaN propagation changed.');

    infInput = amplitude;
    infInput(3, 4) = Inf;
    infOutput = oce.motion.estimateLoupasPhaseIncrement(infInput, 3);
    assert(nnz(isnan(infOutput)) == 2 && ~any(isinf(infOutput), 'all'), ...
        'Loupas Inf behavior changed.');

    singleOutput = oce.motion.estimateLoupasPhaseIncrement(single(amplitude), 3);
    assert(isa(singleOutput, 'single'), ...
        'Loupas single precision was not preserved.');
    assert(isequal(size(singleOutput), [4 6]), ...
        'Loupas single output size changed.');

    evenOutput = oce.motion.estimateLoupasPhaseIncrement(amplitude, 2);
    assert(isequal(size(evenOutput), [5 6]), ...
        'Loupas even-M output size changed.');
    assertExactNumericContract(0.16733675286210495, evenOutput(1, 1), ...
        'Loupas.M2.first');
    oddOutput = oce.motion.estimateLoupasPhaseIncrement(amplitude, 3);
    assert(isequal(size(oddOutput), [4 6]), ...
        'Loupas odd-M output size changed.');

    shortInput = exp(-1i * (0.1 * (1:2)' + 0.17 * (1:3)));
    assertExactNumericContract( ...
        [0.16733675286210498 0.16733675286210486], ...
        oce.motion.estimateLoupasPhaseIncrement(shortInput, 2), ...
        'Loupas.short');

    assert_error(@() oce.motion.estimateLoupasPhaseIncrement(amplitude, 1), ...
        'MATLAB:sizeDimensionsMustMatch');
    assert_error(@() oce.motion.estimateLoupasPhaseIncrement(amplitude, 0), ...
        'MATLAB:sizeDimensionsMustMatch');
    largeMOutput = oce.motion.estimateLoupasPhaseIncrement(amplitude, 7);
    assert(isa(largeMOutput, 'double') && ...
        isequal(size(largeMOutput), [0 6]), ...
        'Loupas M larger than the axial dimension changed behavior.');

    intentional = amplitudeOutput;
    intentional(1) = intentional(1) + 0.01;
    assert_difference_detected(amplitudeOutput, intentional, ...
        'Loupas.intentional.Sample');
end

function assert_error(callback, expectedIdentifier)
    try
        callback();
    catch ME
        assert(strcmp(ME.identifier, expectedIdentifier), ...
            'Expected error %s; actual=%s.', expectedIdentifier, ME.identifier);
        return;
    end
    error('OCE:LoupasTest:MissingError', ...
        'Expected error %s was not raised.', expectedIdentifier);
end

function assert_difference_detected(expected, actual, path)
    try
        assertExactNumericContract(expected, actual, path);
    catch ME
        assert(strcmp(ME.identifier, 'OCE:Contract:Difference'), ...
            'Unexpected negative-control error: %s.', ME.identifier);
        assert(contains(ME.message, 'absolute tolerance=0'), ...
            'Negative-control diagnostics omitted the tolerance.');
        return;
    end
    error('OCE:LoupasTest:NegativeControl', ...
        'Intentional Loupas difference was not detected.');
end
