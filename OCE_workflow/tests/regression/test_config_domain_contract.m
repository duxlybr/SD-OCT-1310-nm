end

function persist_acquisition_params(fixture)
    oce.io.loadExperimentalLog( ...
        fixture.logPath, 'SaveAcquisitionParams', true);
end

function assert_save_contract()
    root = tempname;
    mkdir(root);
    cleanup = onCleanup(@() remove_tree(root));
    config = oce.config.getDefaultProcessingConfig("phantom");
    pathValue = oce.config.saveProcessingConfig(root, "synthetic", config);
    if ~isfile(pathValue)
        error('OCE:ConfigTest:SaveContract', ...
            'ProcessingConfig file was not persisted.');
    end
    info = whos('-file', pathValue);
    if numel(info) ~= 1 || string(info.name) ~= "processing_config" || ...
            string(info.class) ~= "struct" || ~isequal(info.size, [1 1])
        error('OCE:ConfigTest:SaveContract', ...
            'ProcessingConfig MAT contract changed.');
    end
    loaded = load(pathValue, 'processing_config');
    if ~isequaln(loaded.processing_config, config)
        error('OCE:ConfigTest:SaveContract', ...
            'Persisted ProcessingConfig differs from the supplied config.');
    end
    clear cleanup
end

function assert_build_errors()
    assert_throws(@() oce.config.buildProcessingConfigForAcquisition([]));
    assert_identifier('OCE:Config:UnsupportedBuildOption', @() ...
        oce.config.buildProcessingConfigForAcquisition( ...
            struct('x', 1), 'Unexpected', true));

    fixture = create_io_acquisition_fixture();
    persist_acquisition_params(fixture);
    inputs = oce.acquisition.prepareProcessingInputs( ...
        fixture.root, fixture.subExperiment, "R004", ...
        'Key', 'run_id', 'RequireProcessingConfig', true);
    missing = rmfield(inputs, 'processing_config');
    assert_throws(@() oce.config.buildProcessingConfigForAcquisition(missing));
    empty = inputs; empty.processing_config = struct();
    assert_throws(@() oce.config.buildProcessingConfigForAcquisition(empty));
    clear fixture
end

function assert_identifier(expected, callback)
    try
        callback();
    catch ME
        if string(ME.identifier) == string(expected), return; end
        error('OCE:ConfigTest:WrongIdentifier', ...
            'Expected %s, actual %s.', expected, ME.identifier);
    end
    error('OCE:ConfigTest:MissingError', ...
        'Expected error %s was not raised.', expected);
end

function assert_throws(callback)
    try
        callback();
    catch
        return;
    end
    error('OCE:ConfigTest:MissingError', 'Expected an error but none was raised.');
end

function remove_tree(folder)
    if isfolder(folder), rmdir(folder, 's'); end
end
