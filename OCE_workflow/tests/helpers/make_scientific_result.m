function result = make_scientific_result(frequencyHz, diagnostics, ...
        curves, angularPhaseSpeed, angularThicknessMm, anglesDeg)
%MAKE_SCIENTIFIC_RESULT Build a lightweight valid schema-v3 test fixture.

    frequencyHz = frequencyHz(:);
    angularPhaseSpeed = angularPhaseSpeed(:);
    angularThicknessMm = angularThicknessMm(:);
    anglesDeg = anglesDeg(:);
    count = numel(angularPhaseSpeed);
    if mod(count, 2) ~= 0 || numel(diagnostics) ~= count || ...
            numel(curves) ~= count
        error('OCE:ResultFixture:InvalidInput', ...
            'Fixture directions must contain complete left/right pairs.');
    end
    scanAxisCount = count / 2;
    directions = repmat(empty_direction(), count, 1);
    names = ["left", "right"];
    for index = 1:count
        curve = curves{index}(:);
        diagnostic = diagnostics{index}(:);
        selected = 1;
        curve(selected) = angularPhaseSpeed(index);
        requested = frequencyHz(selected);
        selectedSpeed = curve(selected);
        if isfinite(selectedSpeed) && selectedSpeed ~= 0
            selectedWavenumber = requested / selectedSpeed;
        else
            selectedWavenumber = NaN;
        end
        directions(index) = struct( ...
            'scan_axis_index', ceil(index / 2), ...
            'direction', names(mod(index - 1, 2) + 1), ...
            'spectrum', struct('quantity', ...
                "mean_temporal_fft_magnitude_across_lateral_samples", ...
                'units', "arbitrary_magnitude", 'layout', "frequency", ...
                'temporal_diagnostic_magnitude', diagnostic), ...
            'ridge', struct(), ...
            'phase_speed_curve', struct('quantity', "phase_speed", ...
                'units', "m/s", 'layout', "frequency", ...
                'smoothed_phase_speed_m_per_s', curve), ...
            'target_selection', struct( ...
                'requested_frequency_hz', requested, ...
                'selected_bin_index', selected, ...
                'selected_frequency_hz', frequencyHz(selected), ...
                'frequency_error_hz', 0, ...
                'selected_wavenumber_per_m', selectedWavenumber, ...
                'selected_phase_speed_m_per_s', curve(selected)), ...
            'mean_thickness_mm', angularThicknessMm(index));
    end
    [phaseMean, phaseStd, phaseRange] = ...
        oce.results.computeScalarStatistics(angularPhaseSpeed);
    [thicknessMean, thicknessStd, thicknessRange] = ...
        oce.results.computeScalarStatistics(angularThicknessMm * 1e3);
    requestedFrequencyHz = ...
        directions(1).target_selection.requested_frequency_hz;
    processingConfig = struct( ...
        'AcquisitionOptions', struct('scan_geometry', "angular_bmodes"), ...
        'DispersionWindowOptions', struct( ...
            'spatial', struct('method', "fraction_of_bmode")));
    bmodes = repmat(struct('index', []), 1, scanAxisCount);
    for index = 1:scanAxisCount
        bmodes(index).index = index;
    end
    scanAxisAnglesDeg = ...
        0:180 / scanAxisCount:180 / scanAxisCount * (scanAxisCount - 1);
    windows = synthetic_windows(bmodes, requestedFrequencyHz, scanAxisCount);

    result = struct( ...
        'schema', struct('name', "oce_phase_speed_result", 'version', 3), ...
        'acquisition', struct('experiment_id', "synthetic", ...
            'subexperiment_id', "results", 'run_id', "R001", ...
            'sample_type', "phantom", 'protocol', "angular_bmodes", ...
            'source_row', struct('scan_geometry', "angular_bmodes")), ...
        'processing', struct('config', processingConfig), ...
        'borders', struct('quantity', ...
            "mean_physical_thickness_per_directional_dispersion_window", ...
            'units', "mm", 'layout', "direction", ...
            'ordering', "acquisition_direction_order", ...
            'directional_mean_thickness_mm', angularThicknessMm), ...
        'windows', windows, ...
        'dispersion', struct('target_frequency', struct( ...
                'source', "resolved_filter_center", 'requested_hz', requestedFrequencyHz), ...
            'direction_ordering', "acquisition_direction_order", ...
            'scan_axis_angles_deg', scanAxisAnglesDeg, 'scan_axis_count', scanAxisCount, ...
            'directions', rmfield(directions, {'spectrum', 'ridge', ...
                'phase_speed_curve', 'target_selection', 'mean_thickness_mm'}), ...
            'estimators', struct('kf_ridge', struct('method', "windowed_fft_ridge", ...
                'frequency_axis_hz', frequencyHz, 'frequency_axis_quantity', "temporal_frequency", ...
                'frequency_axis_units', "Hz", 'frequency_axis_layout', "frequency", ...
                'directions', rmfield(directions, {'scan_axis_index', 'direction', 'mean_thickness_mm'})), ...
                'phase_gradient', struct('enabled', false, ...
                    'frequency_source', "acquisition_row.frequency_Hz", ...
                    'target_frequency_reference', "dispersion.target_frequency.requested_hz", ...
                    'input', struct(), 'directions', struct([])))), ...
        'angular', struct('unit', "deg", 'layout', "angle", ...
            'ordering', "counterclockwise_full_circle", ...
            'full_circle_angles_deg', anglesDeg, ...
            'source_direction_indices', (1:count)', ...
            'phase_speed_m_per_s', angularPhaseSpeed, ...
            'mean_thickness_mm', angularThicknessMm), ...
        'statistics', struct( ...
            'phase_speed', struct('quantity', "phase_speed", ...
                'units', "m/s", 'mean_m_per_s', phaseMean, ...
                'standard_deviation_m_per_s', phaseStd, ...
                'range_m_per_s', phaseRange), ...
            'thickness', struct('quantity', "mean_physical_thickness", ...
                'units', "um", 'source_units', "mm", ...
                'conversion_factor', 1e3, 'mean_um', thicknessMean, ...
                'standard_deviation_um', thicknessStd, ...
                'range_um', thicknessRange)));
    for index = 1:numel(directions)
        result.dispersion.estimators.kf_ridge.directions(index).target_selection = ...
            rmfield(directions(index).target_selection, 'requested_frequency_hz');
    end
    oce.results.validateScientificResult(result);
end

function windows = synthetic_windows(bmodes, frequencyHz, scanAxisCount)
    windows = struct( ...
        'source', struct( ...
            'quantity', "phase_increment", ...
            'units', "rad", ...
            'layout', "lateral_time", ...
            'filter_enabled', false, ...
            'filter_applied', false, ...
            'signal_size', [scanAxisCount, 2]), ...
        'frequency', struct('center_hz', frequencyHz), ...
        'sample_interval_s', 1, ...
        'resolved_options', struct( ...
            'spatial', struct('method', "fraction_of_bmode")), ...
        'bmodes', bmodes, ...
        'provenance', struct( ...
            'source', "synthetic_fixture", ...
            'limitations', strings(0, 1)));
end

function value = empty_direction()
    value = struct('scan_axis_index', [], 'direction', "", ...
        'spectrum', struct(), 'ridge', struct(), ...
        'phase_speed_curve', struct(), 'target_selection', struct(), ...
        'mean_thickness_mm', []);
end
