function result = make_reconstruction_result(amplitude, ...
        localLateralAxisMm, depthAxisMm, timeAxisS)
%MAKE_RECONSTRUCTION_RESULT Build a lightweight valid reconstruction fixture.

    if nargin < 4
        timeAxisS = 0;
    end
    if numel(localLateralAxisMm) ~= size(amplitude, 2)
        error('OCE:TestFixture:InvalidLateralAxis', ...
            'Synthetic lateral axis length must match amplitude width.');
    end
    complexValues = repmat(amplitude', 1, 1, numel(timeAxisS));
    amplitudeValues = mean(abs(complexValues), 3)';
    depthCount = size(amplitude, 1);
    lateralCount = size(amplitude, 2);
    timeCount = numel(timeAxisS);
    result = struct( ...
        'complex_volume', struct( ...
            'values', complex(complexValues), ...
            'quantity', "complex_oct_amplitude", ...
            'units', "arbitrary_complex_amplitude", ...
            'layout', "lateral_depth_time"), ...
        'amplitude', struct('values', amplitudeValues, ...
            'quantity', "mean_temporal_oct_amplitude", ...
            'units', "arbitrary_amplitude", ...
            'layout', "depth_lateral"), ...
        'log_amplitude', struct( ...
            'values', real(20 * log10(amplitudeValues)), ...
            'quantity', "log_oct_amplitude", ...
            'units', "dB_relative", ...
            'layout', "depth_lateral", ...
            'definition', "20*log10(mean_temporal_oct_amplitude)"), ...
        'axes', struct( ...
            'lateral', axis_contract(1:lateralCount, "sample", ...
                "lateral_storage_index", "lateral"), ...
            'depth', axis_contract(depthAxisMm, "mm", ...
                "refractive_corrected_depth", "depth"), ...
            'time', axis_contract(timeAxisS, "s", ...
                "acquisition_time", "time")), ...
        'crop', struct( ...
            'depth', struct( ...
                'start_index_inclusive', 1, ...
                'end_index_inclusive', depthCount, ...
                'sample_count', depthCount), ...
            'time', struct( ...
                'start_index_inclusive', 1, ...
                'end_index_inclusive', timeCount, ...
                'sample_count', timeCount)), ...
        'geometry', struct( ...
            'spectral_sample_count', 2 * depthCount, ...
            'prepared_spectral_sample_count', 2 * depthCount, ...
            'fft_sample_count', 2 * depthCount, ...
            'temporal_repetition_count', timeCount, ...
            'available_depth_sample_count', depthCount, ...
            'lateral_sample_count', lateralCount, ...
            'depth_sample_count', depthCount, ...
            'time_sample_count', timeCount, ...
            'depth_sample_interval_mm', interval(depthAxisMm), ...
            'time_sample_interval_s', interval(timeAxisS)), ...
        'provenance', struct( ...
            'source', "synthetic_fixture", ...
            'window_function', "Hann", ...
            'fft_direction', "forward_along_spectral_axis", ...
            'retained_spectrum', "synthetic_fixture", ...
            'refractive_index', 1, ...
            'refractive_index_source', "synthetic_fixture", ...
            'center_wavelength_um', 1));
    oce.results.validateReconstructionResult(result);
end

function value = axis_contract(values, units, meaning, layout)
    value = struct('values', values, 'units', units, ...
        'meaning', meaning, 'layout', layout);
end

function value = interval(axisValues)
    if numel(axisValues) < 2
        value = NaN;
    else
        value = axisValues(2) - axisValues(1);
    end
end
