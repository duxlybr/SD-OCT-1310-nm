function [logPath, requiredColumns] = create_synthetic_log(root, subExperiment)
    requiredColumns = [ ...
        "experiment_id", "sub_experiment", "run_id", "filename", ...
        "sample_type", "experiment_type", "excitation_type", ...
        "acquisition_mode", "scan_geometry", "oct_system_profile", ...
        "frequency_Hz", "rep_id"];
    optionalColumns = [ ...
        "status", "shape", "material", "proportion", "sample_id", ...
        "period_us", "lead_train", "voltage_mVpp", ...
        "scan_size_x_mm", "scan_size_y_mm", "alines_per_bscan", ...
        "m_repetitions", "bscan_count", ...
        "puff_delay_ms", "puff_on_ms", "puff_frequency_Hz", ...
        "load_id", "strain_percent"];
    columns = [requiredColumns optionalColumns];
    sectionRow = cellstr(build_section_row(columns));
    headerRow = cellstr(columns);
    rowA = make_log_row(columns, subExperiment, ...
        "R004", "synthetic_a.bin", "1200", "1", "A");
    rowB = make_log_row(columns, subExperiment, ...
        "R005", "synthetic_b.bin", "1500", "2", "B");
    logPath = fullfile(root, 'experimental_log.xlsx');
    writecell([sectionRow; headerRow; rowA; rowB], ...
        logPath, 'Sheet', 'Experiment');
end

function sections = build_section_row(columns)
    sections = repmat("Experiment", size(columns));
    sampleColumns = ["sample_type", "shape", "material", ...
        "proportion", "sample_id"];
    excitationColumns = ["excitation_type", "frequency_Hz", ...
        "period_us", "lead_train", "voltage_mVpp", ...
        "puff_delay_ms", "puff_on_ms", "puff_frequency_Hz"];
    acquisitionColumns = ["run_id", "filename", "acquisition_mode", ...
        "scan_geometry", "oct_system_profile", "rep_id", ...
        "scan_size_x_mm", "scan_size_y_mm", "alines_per_bscan", ...
        "m_repetitions", "bscan_count"];
    sections(ismember(columns, sampleColumns)) = "Sample";
    sections(ismember(columns, excitationColumns)) = "Excitation";
    sections(ismember(columns, acquisitionColumns)) = "Acquisition";
end

