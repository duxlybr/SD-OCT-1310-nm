function create_parser_faithful_oct2_file(path, sampleCountAdjustment)
    if nargin < 2
        sampleCountAdjustment = 0;
    end
    labels = ["header", "acquisition_datetime", "sample_trigger_source", ...
        "sample_rate_MHz", "samples_in_Aline", "pre_trigger_samples", ...
        "pattern_control", "type", "Alines_in_Bframe", "Flyback_Aline_No", ...
        "Bframe_trigger_Aline_delay", "Bframes_in_3Dscan", "No_3Dscans", ...
        "Hor_scan_length_mm", "Ver_scan_length_mm", "use_background_scan", ...
        "use_reference_MZI_scan", "use_dual_edge_sampling_if_external", ...
        "Max_Alines_in_buffer", "Is_Calib_on", "No_calib_scan"];
    values = ["ignored", "2026-01-01T00:00:00", "internal", "100", "8", ...
        "0", "raster", "Raster", "4", "0", "0", "3", "2", "1.5", ...
        "2.5", "0", "0", "0", "4", "0", "0"];
    header = '';
    for idx = 1:numel(labels)
        header = [header char(labels(idx)) ': ' char(values(idx)) ...
            '  ' sprintf('\r\n')]; %#ok<AGROW>
    end
    fileID = fopen(path, 'w');
    if fileID < 0
        error('Could not create synthetic OCT2 fixture: %s', path);
    end
    cleanup = onCleanup(@() fclose(fileID));
    fwrite(fileID, uint16(numel(header)), 'uint16');
    fwrite(fileID, uint16(0), 'uint16');
    fwrite(fileID, uint8(header), 'uint8');
    sampleCount = 8 * 4 * 3 * 2 + sampleCountAdjustment;
    fwrite(fileID, uint16(1:sampleCount), 'uint16');
    clear cleanup
end

function expectedRaw = create_compact_oct2_file( ...
        path, reportedSamples, sampleCountAdjustment, omittedLabel, ...
        trailingByteCount)
    if nargin < 5
        trailingByteCount = 0;
    end
    spectralCount = 8;
    temporalCount = 100;
    bmodeCount = 2;
    spatialCount = 4;
    labels = [ ...
        "Date/Time scan acquisition start"; ...
        "Sample trigger source"; ...
        "# spectral samples per A-line"; ...
        "# pre-trigger samples"; ...
        "Scan type"; ...
        "A-lines per B-frame"; ...
        "Flyback duration in # A-lines"; ...
        "B-frame trigger delay in # A-lines"; ...
        "# of B-frames in 3D scan"; ...
        "# of 3D repeated scans"; ...
        "Horizontal scan length (mm)"; ...
        "Vertical scan length (mm)"; ...
        "Background subtraction"];
    values = [ ...
        "2026-08-15 12:00:00"; "Internal"; string(reportedSamples); ...
        "4"; "Raster"; string(temporalCount); "1"; "2"; ...
        string(bmodeCount); string(spatialCount); "10.000"; ...
        "10.000"; "0"];
    keep = labels ~= string(omittedLabel);
    labels = labels(keep);
    values = values(keep);
    header = '';
    for index = 1:numel(labels)
        header = [header char(labels(index)) ': ' char(values(index)) ...
            '; ' char(13)]; %#ok<AGROW>
    end

    sourceRaw = reshape(uint16(1:(spectralCount * temporalCount * ...
        spatialCount * bmodeCount)), spectralCount, temporalCount, ...
        spatialCount, bmodeCount);
    payload = sourceRaw(:);
    payload = payload(1:(numel(payload) + sampleCountAdjustment));
    fileID = fopen(path, 'w');
    if fileID < 0
        error('Could not create synthetic compact OCT2 fixture: %s', path);
    end
    cleanup = onCleanup(@() fclose(fileID));
    fwrite(fileID, uint16(numel(header)), 'uint16');
    fwrite(fileID, uint16(0), 'uint16');
    fwrite(fileID, uint8(header), 'uint8');
    fwrite(fileID, payload, 'uint16');
    fwrite(fileID, repmat(uint8(255), trailingByteCount, 1), 'uint8');
    clear cleanup

    expectedRaw = double(reshape(sourceRaw, spectralCount, ...
        temporalCount, spatialCount * bmodeCount));
end

