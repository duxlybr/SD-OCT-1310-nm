function fixture = create_io_acquisition_fixture()
%CREATE_IO_ACQUISITION_FIXTURE Build lightweight deterministic I/O inputs.

    fixture = struct();
    fixture.root = tempname;
    mkdir(fixture.root);
    fixture.cleanup = onCleanup(@() remove_tree(fixture.root));
    fixture.subExperiment = 'synthetic_subexperiment';
    fixture.dataDir = fullfile(fixture.root, 'Data', fixture.subExperiment);
    fixture.paramsDir = fullfile(fixture.root, 'Params', fixture.subExperiment);
    mkdir(fixture.dataDir);
    mkdir(fixture.paramsDir);

    [fixture.logPath, fixture.expectedColumns] = create_synthetic_log( ...
        fixture.root, fixture.subExperiment);
    create_parser_faithful_oct2_file( ...
        fullfile(fixture.dataDir, 'synthetic_a.bin'));
    create_parser_faithful_oct2_file( ...
        fullfile(fixture.dataDir, 'synthetic_b.bin'));

    acquisition_parameters = create_acquisition_parameters();
    save(fullfile(fixture.paramsDir, ...
        'Params_synthetic_subexperiment.mat'), 'acquisition_parameters');
    processing_config = oce.config.getDefaultProcessingConfig("phantom");
    oce.config.saveProcessingConfig( ...
        fixture.root, fixture.subExperiment, processing_config);

    fixture.rawDir = fullfile(fixture.root, 'raw');
    mkdir(fixture.rawDir);
    fixture.rawFilename = 'minimal_oct2.bin';
    create_parser_faithful_oct2_file( ...
        fullfile(fixture.rawDir, fixture.rawFilename));
    fixture.compactFilename = 'compact_oct2.bin';
    fixture.compactExpectedRaw = create_compact_oct2_file( ...
        fullfile(fixture.rawDir, fixture.compactFilename), 1, 0, "");
    fixture.octoceFilename = 'octoce_raw_v1.bin';
    % The DG4162 GUI records the generator in the .bin header.
    fixture.generatorFrequencyHz = 1250;
    fixture.octoceExpectedRaw = create_octoce_raw_v1_file( ...
        fullfile(fixture.rawDir, fixture.octoceFilename), struct(), ...
        generator_section(fixture.generatorFrequencyHz));
    % One synthetic file per GUI MB scan pattern; expected raw data are in
    % forward A-line order.
    fixture.octocePatterns = struct();
    fixture.octocePatterns.crosshair = create_octoce_pattern(fixture.rawDir, ...
        'octoce_crosshair.bin', struct('pattern', 'crosshair', 'bscans', 1, ...
        'x_length_mm', 2, 'y_length_mm', 2));
    fixture.octocePatterns.linear = create_octoce_pattern(fixture.rawDir, ...
        'octoce_linear.bin', struct('pattern', 'linear', 'bscans', 2, ...
        'orientation', 'vertical', 'linear_bidirectional', true, ...
        'x_length_mm', 1, 'y_length_mm', 3));
    fixture.octocePatterns.raster = create_octoce_pattern(fixture.rawDir, ...
        'octoce_raster_bidirectional.bin', struct('pattern', 'raster', ...
        'bscans', 3, 'raster_bidirectional', true, ...
        'x_length_mm', 2, 'y_length_mm', 1));
    fixture.octocePatterns.rings = create_octoce_pattern(fixture.rawDir, ...
        'octoce_rings.bin', struct('pattern', 'rings', 'bscans', 2, ...
        'alines', 8, 'x_length_mm', 2, 'y_length_mm', 2));
    fixture.octocePatterns.spiral = create_octoce_pattern(fixture.rawDir, ...
        'octoce_spiral.bin', struct('pattern', 'spiral', 'bscans', 2, ...
        'alines', 8, 'x_length_mm', 2, 'y_length_mm', 2));
    fixture.octoceBmFilename = 'octoce_bm.bin';
    create_octoce_raw_v1_file(fullfile(fixture.rawDir, ...
        fixture.octoceBmFilename), struct('mode', 'BM'));
    fixture.truncatedRawFilename = 'truncated_oct2.bin';
    create_parser_faithful_oct2_file( ...
        fullfile(fixture.rawDir, fixture.truncatedRawFilename), -1);
    fixture.trailingRawFilename = 'trailing_oct2.bin';
    create_parser_faithful_oct2_file( ...
        fullfile(fixture.rawDir, fixture.trailingRawFilename), 1);
    fixture.compactTrailingByteFilename = 'compact_trailing_byte.bin';
    create_compact_oct2_file(fullfile(fixture.rawDir, ...
        fixture.compactTrailingByteFilename), 1, 0, "", 1);
    fixture.compactNonIntegerFilename = 'compact_noninteger.bin';
    create_compact_oct2_file(fullfile(fixture.rawDir, ...
        fixture.compactNonIntegerFilename), 1, -1, "");
    fixture.compactMissingFieldFilename = 'compact_missing_field.bin';
    create_compact_oct2_file(fullfile(fixture.rawDir, ...
        fixture.compactMissingFieldFilename), 1, 0, ...
        "A-lines per B-frame");
    fixture.unknownHeaderFilename = 'unknown_header.bin';
    create_unknown_oct2_file(fullfile(fixture.rawDir, ...
        fixture.unknownHeaderFilename));

    fixture.complexMeasurement = struct();
    fixture.complexMeasurement.rawdata = reshape( ...
        double(1:(8 * 4 * 3)), 8, 4, 3);
    fixture.integerMeasurement = fixture.complexMeasurement;
    fixture.integerMeasurement.rawdata = uint16( ...
        fixture.integerMeasurement.rawdata);
    fixture.OCT_system = oce.config.resolveOCTSystemOptions( ...
        oce.config.getOCTSystemOptions("swept_source_1300"));
    fixture.sample_optics = oce.config.resolveSampleOpticalOptions( ...
        oce.config.getDefaultProcessingConfig("phantom").SampleOpticalOptions);
    fixture.geometry = struct( ...
        'spectral_sample_count', 8, ...
        'temporal_repetition_count', 4, ...
        'available_depth_sample_count', 4, ...
        'lateral_sample_count', 3, ...
        'bmode_count', 1, ...
        'samples_per_bmode', 3, ...
        'bmode_scan_width_mm', 1, ...
        'bmode_lateral_axis_mm', linspace(0, 1, 3), ...
        'lateral_sample_interval_mm', 0.5, ...
        'depth_sample_count', 3, 'time_sample_count', 4);
    fixture.resolved_crop = struct( ...
        'depth', struct('selection', "manual_indices", ...
            'start_index_inclusive', 2, 'end_index_inclusive', 4, ...
            'sample_count', 3), ...
        'time', struct('selection', "manual_indices", ...
            'start_index_inclusive', 1, 'end_index_inclusive', 4, ...
            'sample_count', 4), ...
        'selection_source', "acquisition_parameters");
end

