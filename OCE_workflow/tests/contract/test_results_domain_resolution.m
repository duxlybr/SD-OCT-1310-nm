function test_results_domain_resolution(context)
%TEST_RESULTS_DOMAIN_RESOLUTION Verify canonical results-domain ownership.

    canonical = {
        'oce.pipeline.runSubexperimentSummary', 'src/+oce/+pipeline/runSubexperimentSummary.m';
        'oce.pipeline.runExperimentSummary', 'src/+oce/+pipeline/runExperimentSummary.m';
        'oce.results.buildSubexperimentResultSet', 'src/+oce/+results/buildSubexperimentResultSet.m';
        'oce.results.buildExperimentResultSet', 'src/+oce/+results/buildExperimentResultSet.m';
        'oce.results.alignDispersionFrequencies', 'src/+oce/+results/alignDispersionFrequencies.m';
        'oce.results.summarizeRepetitions', 'src/+oce/+results/summarizeRepetitions.m';
        'oce.results.summarizeDispersionSamples', 'src/+oce/+results/summarizeDispersionSamples.m';
        'oce.results.summarizeAngles', 'src/+oce/+results/summarizeAngles.m';
        'oce.results.summarizeScanAxes', 'src/+oce/+results/summarizeScanAxes.m';
        'oce.results.formatConditionLabel', 'src/+oce/+results/formatConditionLabel.m';
        'oce.results.buildConditionSummaryTable', 'src/+oce/+results/buildConditionSummaryTable.m';
        'oce.results.buildScanAxisSummaryTable', 'src/+oce/+results/buildScanAxisSummaryTable.m';
        'oce.results.validateReconstructionResult', 'src/+oce/+results/validateReconstructionResult.m';
        'oce.io.exportConditionSummaryTable', 'src/+oce/+io/exportConditionSummaryTable.m';
        'oce.io.exportScanAxisSummaryTable', 'src/+oce/+io/exportScanAxisSummaryTable.m';
        'oce.io.saveResultsSummary', 'src/+oce/+io/saveResultsSummary.m'};
    assert_unique_locations(canonical, context.repoRoot);

    retiredAxisToken = "Mer" + "idian";
    assert_absent(["buildExperimentDataFromAcquisitionTable", ...
        "buildExperimentDataFromSubexperiments", ...
        "alignExperimentFrequencies", "alignExperimentFrequencyGlobal", ...
        "summarizeExperimentRepetitions", "summarizeExperimentAngles", ...
        "summarizePhysical" + retiredAxisToken + "s", ...
        "export_results_summary_table", ...
        "formatExperimentConditionLabel", "run_results_summary", ...
        "oce.results.buildExperimentDataFromAcquisitionTable", ...
        "oce.results.buildExperimentDataFromSubexperiments", ...
        "oce.results.alignExperimentFrequencies", ...
        "oce.results.buildSummaryTable", ...
        "oce.results.build" + retiredAxisToken + "SummaryTable", ...
        "oce.results.summarizePhysical" + retiredAxisToken + "s", ...
        "oce.results.buildPhysical" + retiredAxisToken + "SummaryTable", ...
        "oce.io.exportResultsSummaryTable", ...
        "oce.io.exportExperiment" + retiredAxisToken + "SummaryTable", ...
        "oce.io.exportPhysical" + retiredAxisToken + "SummaryTable"]);
    if ~isempty(which('oce.results.runResultsSummary', '-all'))
        error('OCE:ResultsContract:RetiredAdapter', ...
            'Retired results-package coordinator still resolves.');
    end

    packageFiles = [ ...
        dir(fullfile(context.repoRoot, 'src', '+oce', '+results', '*.m')); ...
        dir(fullfile(context.repoRoot, 'src', '+oce', '+io', ...
            'exportConditionSummaryTable.m')); ...
        dir(fullfile(context.repoRoot, 'src', '+oce', '+io', ...
            'exportScanAxisSummaryTable.m')); ...
        dir(fullfile(context.repoRoot, 'src', '+oce', '+io', ...
            'saveResultsSummary.m'))];
    forbidden = '\\<(eval|evalin|assignin|cd)\\s*\\(';
    for idx = 1:numel(packageFiles)
        pathValue = fullfile(packageFiles(idx).folder, packageFiles(idx).name);
        if ~isempty(regexp(fileread(pathValue), forbidden, 'once'))
            error('OCE:ResultsContract:ImplicitState', ...
                'Forbidden implicit-state API found in %s.', pathValue);
        end
    end

    resultNames = string({dir(fullfile(context.repoRoot, 'src', '+oce', ...
        '+results', '*.m')).name});
    if any(startsWith(resultNames, 'plot', 'IgnoreCase', true))
        error('OCE:ResultsContract:PlottingScope', ...
            'Plotting implementations must not live in the results package.');
    end

    assert_human_traceability_ownership(context.repoRoot);
end

function assert_human_traceability_ownership(repoRoot)
    coordinatorPath = fullfile(repoRoot, 'src', '+oce', '+pipeline', ...
        'runSubexperimentSummary.m');
    builderPath = fullfile(repoRoot, 'src', '+oce', '+results', ...
        'buildSubexperimentResultSet.m');
    experimentBuilderPath = fullfile(repoRoot, 'src', '+oce', '+results', ...
        'buildExperimentResultSet.m');
    coordinator = fileread(coordinatorPath);
    builder = fileread(builderPath);
    experimentBuilder = fileread(experimentBuilderPath);

    retiredOptions = ["LoadFile", "ResultFolderKey", "FieldsCellVectors", ...
        "FieldsAngleVectors", "FieldsCopy"];
    for index = 1:numel(retiredOptions)
        if contains(coordinator, retiredOptions(index))
            error('OCE:ResultsContract:RetiredConfiguration', ...
                'runSubexperimentSummary still exposes retired option %s.', ...
                retiredOptions(index));
        end
    end

    if ~contains(builder, 'oce.io.loadAcquisitionTable') || ...
            contains(builder, 'function acquisitionTable = load_acquisition_table')
        error('OCE:ResultsContract:AcquisitionTableOwnership', ...
            ['Result assembly must reuse oce.io.loadAcquisitionTable and must ' ...
             'not own a parallel MAT loader.']);
    end
    if ~contains(experimentBuilder, ...
            'oce.results.buildSubexperimentResultSet') || ...
            contains(experimentBuilder, 'oce.io.loadScientificResult')
        error('OCE:ResultsContract:ExperimentAssemblyOwnership', ...
            ['Experiment-wide assembly must combine maintained sub-experiment ' ...
             'result sets rather than duplicate persisted-result loading.']);
    end
end

function assert_absent(names)
    for idx = 1:numel(names)
        if ~isempty(which(char(names(idx)), '-all'))
            error('OCE:ResultsContract:RetiredAdapter', ...
                'Retired adapter still resolves: %s.', names(idx));
        end
    end
end

function assert_unique_locations(expected, repoRoot)
    for idx = 1:size(expected, 1)
        locations = string(which(expected{idx, 1}, '-all'));
        locations = locations(strlength(locations) > 0);
        if numel(locations) ~= 1
            error('OCE:ResultsContract:Resolution', ...
                'Expected one definition for %s; actual count=%d.', ...
                expected{idx, 1}, numel(locations));
        end
        expectedPath = fullfile(repoRoot, expected{idx, 2});
        if ~strcmpi(normalize_path(locations), normalize_path(expectedPath))
            error('OCE:ResultsContract:Resolution', ...
                '%s expected at %s; actual=%s.', ...
                expected{idx, 1}, expectedPath, locations);
        end
    end
end

function value = normalize_path(value)
    value = replace(string(value), ["/", "\\"], filesep);
end
