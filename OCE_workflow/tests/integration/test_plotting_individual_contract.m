end

function assert_filter_passthrough_preview(fixture, previewGeometry)
    disabledRoot = fullfile(fixture.rootDir, 'disabled_filter_preview');
    mkdir(disabledRoot);
    disabled = fixture.filterResult;
    disabled.applied = false;
    disabled.design.applied = false;
    disabled.design.coefficients = [];
    disabled.design.delay_samples = 0;
    disabled.surface.values = fixture.inputSurfacePhase.values;
    disabled.surface_postprocessed.units = "rad";
    before = findall(groot, 'Type', 'figure');
    reconstruction = make_reconstruction_result( ...
        fixture.Bmode, fixture.Xaxis, fixture.Zaxis, ...
        fixture.filterResult.time_axis_s);
    phaseResult = struct('surface', fixture.inputSurfacePhase);
    oce.plotting.saveFilterPreviews( ...
        phaseResult, disabled, reconstruction, previewGeometry, disabledRoot);
    created = setdiff(findall(groot, 'Type', 'figure'), before);
    legends = findall(created, 'Type', 'Legend');
    labels = strings(0, 1);
    for index = 1:numel(legends)
        labels = [labels; string(legends(index).String(:))]; %#ok<AGROW>
    end
    if ~any(contains(lower(labels), "passthrough"))
        error('OCE:PlottingTest:MissingPassthroughLabel', ...
            'Disabled filtering preview must identify passthrough explicitly.');
    end
    close(created);
end

function assert_enface_motion(rootDir)
    % Raster storage: fast-axis A-lines within each B-scan, then B-scans.
    samplesPerBmode = 4;
    bmodeCount = 3;
    timeCount = 9;
    delaySamples = 2;
    [fastIndex, slowIndex] = ndgrid(1:samplesPerBmode, 1:bmodeCount);
    spatialCode = 10 * slowIndex(:) + fastIndex(:);
    surfaceValues = spatialCode .* sin(0.7 * (1:timeCount));
    geometry = struct( ...
        'samples_per_bmode', samplesPerBmode, ...
        'bmode_count', bmodeCount, ...
        'bmode_lateral_axis_mm', linspace(0, 3, samplesPerBmode), ...
        'raster', struct('slow_axis_mm', linspace(0, 2, bmodeCount)));
    filterResult = struct( ...
        'applied', true, ...
        'surface', struct('values', surfaceValues, ...
            'quantity', "phase_increment", 'units', "rad"), ...
        'design', struct('delay_samples', delaySamples), ...
        'invalid_rows', struct('mask', [true; false(11, 1)]));
    reconstruction = struct( ...
        'crop', struct('time', struct('start_index_inclusive', 5)), ...
        'geometry', struct('time_sample_interval_s', 2e-5));

    data = oce.plotting.prepareEnfaceMotionVisualization( ...
        filterResult, reconstruction, geometry, 'MedianWindow', []);
    retained = surfaceValues(:, delaySamples + 1:end);
    retained = retained - mean(retained, 2);
    expectedFrames = permute(reshape(retained, samplesPerBmode, ...
        bmodeCount, []), [2 1 3]);
    expectedFrames(1, 1, :) = NaN;
    expectedTimeS = (5 + (0:timeCount - delaySamples - 1) - 0.5) * 2e-5;
    if ~isequal(size(data.frames), [bmodeCount samplesPerBmode ...
                timeCount - delaySamples]) || ...
            max(abs(data.frames(2:end) - expectedFrames(2:end)), [], 'all') > 1e-12 || ...
            any(~isnan(data.frames(1, 1, :))) || data.valid_mask(1, 1) || ...
            ~isequal(data.x_axis_mm, linspace(0, 3, samplesPerBmode)) || ...
            ~isequal(data.y_axis_mm, linspace(0, 2, bmodeCount)) || ...
            max(abs(data.time_axis_s - expectedTimeS)) > 1e-15
        error('OCE:PlottingTest:EnfaceLayout', ...
            'En-face frames must map raster storage to y-by-x-by-time.');
    end

    before = findall(groot, 'Type', 'figure');
    oce.plotting.plotEnfaceMotionSnapshots( ...
        filterResult, reconstruction, geometry, 'SnapshotCount', 3);
    created = setdiff(findall(groot, 'Type', 'figure'), before);
    if numel(created) ~= 1 || numel(findall(created, 'Type', 'Axes')) ~= 3
        error('OCE:PlottingTest:EnfaceSnapshots', ...
            'En-face snapshots must render one figure with requested frames.');
    end
    close(created);

    videoDir = fullfile(rootDir, 'enface_video');
    videoPath = oce.video.createEnfaceMotionVideo( ...
        filterResult, reconstruction, geometry, ...
        struct('time_start_idx', 1, 'max_frames', 3, 'frame_rate', 10, ...
            'filename', "Enface.mp4"), ...
        videoDir, 'ShowProgress', false);
    videoInfo = dir(videoPath);
    if isempty(videoInfo) || videoInfo.bytes <= 0 || ...
            ~isempty(setdiff(findall(groot, 'Type', 'figure'), before))
        error('OCE:PlottingTest:EnfaceVideo', ...
            'En-face video must write one MP4 and close its figure.');
    end
    unfiltered = filterResult;
    unfiltered.applied = false;
    try
        oce.video.createEnfaceMotionVideo(unfiltered, reconstruction, ...
            geometry, struct('time_start_idx', 1, 'max_frames', 1, ...
                'frame_rate', 10, 'filename', "Unused.mp4"), videoDir);
        detected = false;
    catch ME
        detected = strcmp(ME.identifier, 'OCE:Video:FilteringRequired');
    end
    if ~detected
        error('OCE:PlottingTest:EnfaceVideoFilter', ...
            'En-face video must require an applied filter.');
    end

    assert_structural_enface(rootDir, geometry);
end

function assert_structural_enface(rootDir, geometry)
    lateralCount = geometry.samples_per_bmode * geometry.bmode_count;
    depthCount = 5;
    timeCount = 6;
    sampleCount = lateralCount * depthCount * timeCount;
    volume = reshape(complex(1 + mod((1:sampleCount) * 7, 13), ...
        cos(1:sampleCount)), lateralCount, depthCount, timeCount);
    reconstruction = struct( ...
        'complex_volume', struct('values', volume, ...
            'layout', "lateral_depth_time"), ...
        'crop', struct('time', struct('start_index_inclusive', 11)), ...
        'axes', struct('depth', struct('values', (0:depthCount - 1)' * 0.01)));

    enface = oce.acquisition.computeStructuralEnface(reconstruction, geometry, ...
        'AScanAverageCount', 3, 'FirstMRepetition', 12, ...
        'DepthRangeIndices', [2 4]);
    % Amplitude averaged over M-repetitions 12:14 (local 2:4), then depth 2:4.
    expected = mean(mean(abs(volume(:, 2:4, 2:4)), 3), 2);
    expected = reshape(expected, geometry.samples_per_bmode, ...
        geometry.bmode_count).';
    if ~isequal(size(enface.values), [geometry.bmode_count ...
                geometry.samples_per_bmode]) || ...
            max(abs(enface.values - expected), [], 'all') > 1e-12 || ...
            max(abs(enface.log_values - 20 * log10(expected)), [], 'all') > 1e-9 || ...
            enface.a_scan_average.count ~= 3 || ...
            enface.a_scan_average.first_m_repetition ~= 12 || ...
            enface.a_scan_average.last_m_repetition ~= 14 || ...
            ~isequal(enface.depth_average.crop_indices, [2 4]) || ...
            max(abs(enface.depth_average.range_mm - [0.01 0.03])) > 1e-12 || ...
            ~isequal(enface.y_axis_mm, geometry.raster.slow_axis_mm)
        error('OCE:PlottingTest:StructuralEnface', ...
            ['Structural en-face must average N A-scans, then depth, and ' ...
             'map raster storage to y-by-x.']);
    end
    try
        oce.acquisition.computeStructuralEnface(reconstruction, geometry, ...
            'AScanAverageCount', 6, 'FirstMRepetition', 12);
        detected = false;
    catch ME
        detected = strcmp(ME.identifier, 'OCE:Acquisition:InvalidEnfaceAveraging');
    end
    if ~detected
        error('OCE:PlottingTest:StructuralEnfaceRange', ...
            'A-scan averaging beyond the reconstructed repetitions must fail.');
    end

    before = findall(groot, 'Type', 'figure');
    artifacts = oce.plotting.saveStructuralEnface(enface, ...
        fullfile(rootDir, 'structural_enface'));
    created = setdiff(findall(groot, 'Type', 'figure'), before);
    if ~isequal(endsWith(artifacts, [".fig"; ".png"]), [true; true]) || ...
            ~all(arrayfun(@isfile, artifacts)) || numel(created) ~= 1
        error('OCE:PlottingTest:StructuralEnfaceExport', ...
            'Structural en-face must export one figure as FIG and PNG.');
    end
    close(created);
end

function cleanup_test(rootDir, oldVisibility)
    close all force; set(groot, 'defaultFigureVisible', oldVisibility);
    if isfolder(rootDir), rmdir(rootDir, 's'); end
end
