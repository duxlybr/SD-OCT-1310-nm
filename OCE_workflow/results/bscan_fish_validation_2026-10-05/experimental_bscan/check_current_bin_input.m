%% One bounded real BIN input check: current inherited border vs saved peak
outputRoot=fileparts(mfilename('fullpath'));workflowRoot=fileparts(fileparts(fileparts(outputRoot)));
cd(workflowRoot);startup;
sourcePlane='C:/Users/proyecto.pi1081/Desktop/OCE_fish/OCE_estimator_validation/experimental/luis3_bmode1_offset_0p00mm_plane.mat';
old=load(sourcePlane,'data');oldData=old.data;clear old;
loadOptions=oldData.metadata.load_options;
loadOptions.surface_method="inherited_threshold";loadOptions.bmode_index=1;loadOptions.show_progress=false;
data=oce.acquisition.loadWaveMotionPlane(oldData.metadata.source_file,loadOptions);
options=struct('method',"phase_gradient",'frequency_hz',1000,'time_start_s',.002,'time_end_s',.004, ...
    'window_x_mm',.9,'window_row_mm',.04,'min_coherence',.2,'min_amplitude_fraction',.08, ...
    'min_support_fraction',.6,'fit_error_max',.3,'speed_range_m_s',[.2 10],'smoothing_mm',0);
newMap=oce.dispersion.estimateLocalSpeedMap(data,options);
oldMap=oce.dispersion.estimateLocalSpeedMap(oldData,options);
beforePhaseLimit=isfinite(data.structural_db)&data.structural_db>=data.metadata.load_options.intensity_floor_db& ...
    data.coherence>=data.metadata.load_options.coherence_threshold&data.row_m(:)>=data.offsets.surface_z_m;
record=struct('old_surface_method',oldData.metadata.load_options.surface_method, ...
    'new_surface_method',data.metadata.load_options.surface_method, ...
    'old_surface_valid_count',nnz(isfinite(oldData.offsets.surface_z_m)), ...
    'new_surface_valid_count',nnz(isfinite(data.offsets.surface_z_m)), ...
    'old_surface_median_mm',median(oldData.offsets.surface_z_m,'all','omitnan')*1000, ...
    'new_surface_median_mm',median(data.offsets.surface_z_m,'all','omitnan')*1000, ...
    'old_oct_count',nnz(oldData.valid_mask),'new_oct_count',nnz(data.valid_mask), ...
    'new_border_oct_coherence_before_phase_limit_count',nnz(beforePhaseLimit), ...
    'new_max_phase_step_rad',data.metadata.load_options.max_phase_step_rad, ...
    'old_PG_count',nnz(oldMap.valid_mask),'new_PG_count',nnz(newMap.valid_mask), ...
    'old_speed_median_m_s',median(oldMap.speed_m_s,'all','omitnan'), ...
    'new_speed_median_m_s',median(newMap.speed_m_s,'all','omitnan'), ...
    'surface_max_absolute_difference_mm',max(abs(oldData.offsets.surface_z_m-data.offsets.surface_z_m),[],'all','omitnan')*1000, ...
    'native_motion_max_difference_rad',max(abs(double(oldData.motion)-double(data.motion)),[],'all','omitnan'), ...
    'interpretation',"One input check, unverified anatomy/calibration; not experimental accuracy validation");
writetable(struct2table(record),fullfile(outputRoot,'current_bin_input_check.csv'));
save(fullfile(outputRoot,'current_bin_input_check.mat'),'data','loadOptions','options','newMap','oldMap','record','sourcePlane','-v7.3');
fig=figure('Visible','off','Color','w','Position',[20 20 1500 800]);cleanup=onCleanup(@()close(fig)); %#ok<NASGU>
layout=tiledlayout(2,2,'Padding','compact','TileSpacing','compact');
nexttile;imagesc(data.preview.x_m*1000,data.preview.depth_m*1000,data.preview.intensity_db);colorbar;hold on;
plot(oldData.preview.x_m*1000,oldData.preview.surface_m*1000,'r-','LineWidth',1.5);
plot(data.preview.x_m*1000,data.preview.surface_m*1000,'w-','LineWidth',1.5);
title('OCT preview: blanco heredado; rojo máximo previo');xlabel('x (mm)');ylabel('Profundidad OCT (mm)');ylim([0 .6]);clim([-50 0]);
nexttile;plot(data.x_m*1000,data.offsets.surface_z_m*1000,'b-',oldData.x_m*1000,oldData.offsets.surface_z_m*1000,'r-');
title('Bordes candidatos; anatomía no verificada');xlabel('x (mm)');ylabel('Profundidad (mm)');legend('Inherited threshold actual','Max-in-search guardado');
for k=1:2
    ax=nexttile;if k==1,result=oldMap;label='PG de MAT previo';else,result=newMap;label='PG de BIN actual';end
    image=imagesc(data.x_m*1000,data.row_m*1000,result.speed_m_s);image.AlphaData=isfinite(result.speed_m_s);ax.Color=[.84 .84 .84];
    colorbar;clim([.2 10]);ylim([.18 .46]);title(sprintf('%s: %d aceptados; zoom explícito',label,nnz(result.valid_mask)));
    xlabel('x (mm)');ylabel('Profundidad OCT (mm)');
end
title(layout,'Una lectura BIN acotada; controles de estimador iguales. Bordes/máscaras/proveniencia distintas no demuestran exactitud.','Interpreter','none');
exportgraphics(fig,fullfile(outputRoot,'current_bin_input_check.png'),'Resolution',150,'BackgroundColor','white');
clear cleanup;
disp(record);disp('CURRENT_BIN_INPUT_CHECK_FINISHED');
