%% Explicit input sensitivity: candidate maximum and 2*pi increment bound
% This is not a default change or an anatomical/propagation validation.
outputRoot=fileparts(mfilename('fullpath'));workflowRoot=fileparts(fileparts(fileparts(outputRoot)));
cd(workflowRoot);startup;
sourcePlane='C:/Users/proyecto.pi1081/Desktop/OCE_fish/OCE_estimator_validation/experimental/luis3_bmode1_offset_0p00mm_plane.mat';
saved=load(sourcePlane,'data');oldData=saved.data;clear saved;
loadOptions=oldData.metadata.load_options;
loadOptions.surface_method="max_in_search";loadOptions.max_phase_step_rad=2*pi;
loadOptions.bmode_index=1;loadOptions.show_progress=false;
data=oce.acquisition.loadWaveMotionPlane(oldData.metadata.source_file,loadOptions);
options=struct('method',"phase_gradient",'frequency_hz',1000,'time_start_s',.002,'time_end_s',.004, ...
    'window_x_mm',.9,'window_row_mm',.04,'min_coherence',.2,'min_amplitude_fraction',.08, ...
    'min_support_fraction',.6,'fit_error_max',.3,'speed_range_m_s',[.2 10],'smoothing_mm',0);
newMap=oce.dispersion.estimateLocalSpeedMap(data,options);
oldMap=oce.dispersion.estimateLocalSpeedMap(oldData,options);
shared=isfinite(newMap.speed_m_s)&isfinite(oldMap.speed_m_s);
record=struct('surface_method',data.metadata.load_options.surface_method, ...
    'max_phase_step_rad',data.metadata.load_options.max_phase_step_rad, ...
    'surface_valid_count',nnz(isfinite(data.offsets.surface_z_m)), ...
    'oct_support_count',nnz(data.valid_mask),'old_oct_support_count',nnz(oldData.valid_mask), ...
    'PG_accepted_count',nnz(newMap.valid_mask),'old_PG_accepted_count',nnz(oldMap.valid_mask), ...
    'PG_speed_median_m_s',median(newMap.speed_m_s,'all','omitnan'), ...
    'native_phase_max_abs_difference_rad',max(abs(double(data.motion)-double(oldData.motion)),[],'all','omitnan'), ...
    'native_OCT_mask_exact_equal',isequal(data.valid_mask,oldData.valid_mask), ...
    'PG_mask_exact_equal',isequal(newMap.valid_mask,oldMap.valid_mask), ...
    'PG_speed_max_abs_difference_m_s',max(abs(newMap.speed_m_s(shared)-oldMap.speed_m_s(shared)),[],'omitnan'), ...
    'interpretation',"Explicit exploratory candidate surface and increment bound; reproduction does not certify anatomy, repeatability, propagation, Rayleigh mode or accuracy");
writetable(struct2table(record),fullfile(outputRoot,'exploratory_max_surface_input.csv'));
save(fullfile(outputRoot,'exploratory_max_surface_input.mat'),'data','loadOptions','options','newMap','oldMap','record','sourcePlane','-v7.3');
fig=figure('Visible','off','Color','w','Position',[20 20 1450 650]);
layout=tiledlayout(1,2,'Padding','compact','TileSpacing','compact');
for k=1:2
    ax=nexttile;if k==1,result=oldMap;label='MAT previo';else,result=newMap;label='BIN nuevo: máximo candidato, límite 2pi';end
    image=imagesc(data.x_m*1000,data.row_m*1000,result.speed_m_s);image.AlphaData=isfinite(result.speed_m_s);ax.Color=[.84 .84 .84];
    colorbar;clim([.2 10]);ylim([.18 .46]);title(sprintf('%s · %d aceptados',label,nnz(result.valid_mask)));
    xlabel('x local (mm)');ylabel('Profundidad OCT (mm)');
end
title(layout,{'Comparación exploratoria explícita; no se modifica el default conservador', ...
    'Superficie/retardo MB/mode mecánico no verificados. Reproducir un mapa no demuestra propagación ni exactitud.'},'Interpreter','none');
exportgraphics(fig,fullfile(outputRoot,'exploratory_max_surface_input.png'),'Resolution',150,'BackgroundColor','white');close(fig);
disp(record);disp('EXPLORATORY_BIN_INPUT_CHECK_FINISHED');
